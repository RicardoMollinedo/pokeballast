-- Tasks owned by a user (task management API)
create table task (
    id          bigint generated by default as identity primary key,
    owner_id    bigint        not null,
    title       varchar(120)  not null,
    description varchar(2000),
    status      varchar(20)   not null,
    due_date    date,
    version     bigint        not null default 0,
    created_at  timestamp with time zone not null,
    updated_at  timestamp with time zone not null,
    constraint fk_task_owner foreign key (owner_id) references app_user (id) on delete cascade,
    constraint ck_task_status check (status in ('TODO', 'IN_PROGRESS', 'DONE'))
);

-- every query filters by owner (and often by status): keep it indexed
create index ix_task_owner_status on task (owner_id, status);
