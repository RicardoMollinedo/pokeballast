-- Pokemon replicated from PokeAPI (US03) plus our proprietary fields
create table local_pokemon (
    id             bigint generated by default as identity primary key,
    poke_api_id    integer      not null,
    name           varchar(100) not null,
    sprite_url     varchar(500),
    category       varchar(100),
    types          varchar(200) not null,
    abilities      varchar(500) not null,
    height_dm      integer      not null,
    weight_hg      integer      not null,
    localized_name varchar(60),
    region         varchar(60),
    version        bigint       not null default 0,
    synced_at      timestamp with time zone not null,
    updated_at     timestamp with time zone not null,
    constraint uk_local_pokemon_poke_api_id unique (poke_api_id),
    constraint ck_local_pokemon_height check (height_dm >= 0),
    constraint ck_local_pokemon_weight check (weight_hg >= 0)
);

-- Internal classification tags: own table so they can be filtered and indexed
create table local_pokemon_tag (
    pokemon_id bigint      not null,
    position   integer     not null,
    tag        varchar(30) not null,
    constraint pk_local_pokemon_tag primary key (pokemon_id, position),
    constraint fk_local_pokemon_tag_pokemon foreign key (pokemon_id) references local_pokemon (id) on delete cascade
);
create index ix_local_pokemon_tag_tag on local_pokemon_tag (tag);
